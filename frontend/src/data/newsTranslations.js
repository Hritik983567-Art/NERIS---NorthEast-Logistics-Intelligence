export const getLocalizedNewsText = (text, lang = 'en') => {
  if (!text || lang === 'en') return text;

  let translated = text;
  const rules = PHRASE_DICTIONARY[lang];
  if (rules && Array.isArray(rules)) {
    rules.forEach((rule) => {
      translated = translated.replace(rule.pattern, rule.replacement);
    });
  }
  return translated;
};
