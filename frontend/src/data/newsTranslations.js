export const getLocalizedCategory = (cat, lang = 'en') => {
  if (!cat) return cat;
  const key = cat.toUpperCase();
  return CATEGORY_TRANSLATIONS[key]?.[lang] || CATEGORY_TRANSLATIONS[key]?.en || cat;
};

